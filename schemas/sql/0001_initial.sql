-- Initial schema. See docs/adr/0001 (time), 0002 (frames/units), 0003 (storage).
-- Timestamps: *_ns are integer nanoseconds in the named clock domain;
-- *_utc are ISO 8601 strings for humans only.
-- Never edit this file after it is committed; add a new migration instead.

-- Versioned safety and analysis configurations, stored verbatim.
CREATE TABLE configs (
    config_id     TEXT PRIMARY KEY,           -- e.g. "safety-v3"
    kind          TEXT NOT NULL CHECK (kind IN ('safety', 'analysis', 'calibration')),
    sha256        TEXT NOT NULL,
    body          TEXT NOT NULL,              -- the config file as written
    created_utc   TEXT NOT NULL
) STRICT;

CREATE TABLE sessions (
    session_id          TEXT PRIMARY KEY,     -- UUID
    created_utc         TEXT NOT NULL,
    ended_utc           TEXT,
    phase               TEXT NOT NULL CHECK (phase IN ('bench', 'indoor_mount', 'outdoor', 'simulated', 'replay')),
    status              TEXT NOT NULL DEFAULT 'recording'
                        CHECK (status IN ('recording', 'ended', 'accepted', 'rejected', 'incomplete')),
    status_reason       TEXT,
    operator_notes      TEXT,
    schema_version      INTEGER NOT NULL,
    software_versions   TEXT NOT NULL,        -- JSON object: component -> version / git commit
    mac_clock_boot_id   TEXT NOT NULL,        -- identifies the Mac monotonic clock domain
    safety_config_id    TEXT REFERENCES configs (config_id),
    analysis_config_id  TEXT REFERENCES configs (config_id)
) STRICT;

-- A device as it took part in one session.
CREATE TABLE devices (
    session_id                TEXT NOT NULL REFERENCES sessions (session_id),
    device_id                 TEXT NOT NULL,  -- random UUID generated by the app, not a hardware ID
    role                      TEXT NOT NULL CHECK (role IN ('imu_phone', 'mount', 'camera', 'simulator')),
    vendor                    TEXT,
    model                     TEXT,
    os_or_firmware            TEXT,
    app_version               TEXT,
    phone_boot_id             TEXT,           -- identifies the phone monotonic clock domain
    sensor_availability       TEXT,           -- JSON object
    attitude_reference_frame  TEXT,
    requested_interval_s      REAL,
    accel_g0_m_s2             REAL,           -- conversion constant used by the phone (ADR 0002)
    attachment_id             TEXT REFERENCES attachments (attachment_id),
    PRIMARY KEY (session_id, device_id)
) STRICT;

-- Physical phone cradle revisions. Photos live in the private data store.
CREATE TABLE attachments (
    attachment_id        TEXT PRIMARY KEY,
    revision             INTEGER NOT NULL,
    description          TEXT NOT NULL,
    q_ota_from_phone_w   REAL,
    q_ota_from_phone_x   REAL,
    q_ota_from_phone_y   REAL,
    q_ota_from_phone_z   REAL,
    procedure            TEXT,
    evidence_path        TEXT,                -- relative to the private data root
    repeatability_notes  TEXT,
    created_utc          TEXT NOT NULL
) STRICT;

-- Raw four-timestamp exchanges (ADR 0001). Model fits are derived.
CREATE TABLE clock_sync (
    session_id        TEXT NOT NULL REFERENCES sessions (session_id),
    device_id         TEXT NOT NULL,
    exchange_index    INTEGER NOT NULL,
    phone_send_ns     INTEGER NOT NULL,
    mac_receive_ns    INTEGER NOT NULL,
    mac_send_ns       INTEGER NOT NULL,
    phone_receive_ns  INTEGER NOT NULL,
    PRIMARY KEY (session_id, device_id, exchange_index),
    FOREIGN KEY (session_id, device_id) REFERENCES devices (session_id, device_id)
) STRICT;

CREATE TABLE clock_models (
    clock_model_id    TEXT PRIMARY KEY,
    session_id        TEXT NOT NULL REFERENCES sessions (session_id),
    device_id         TEXT NOT NULL,
    method            TEXT NOT NULL,
    software_version  TEXT NOT NULL,
    valid_from_phone_ns  INTEGER NOT NULL,
    valid_to_phone_ns    INTEGER,
    offset_ns         INTEGER NOT NULL,       -- mac_ns = phone_ns + offset + drift * (phone_ns - valid_from)
    drift_ppb         REAL NOT NULL,
    uncertainty_ns    INTEGER NOT NULL,
    residuals         TEXT,                   -- JSON summary
    created_utc       TEXT NOT NULL,
    FOREIGN KEY (session_id, device_id) REFERENCES devices (session_id, device_id)
) STRICT;

-- Raw motion samples. One sequence space per (session, device) across all streams.
CREATE TABLE sensor_samples (
    session_id         TEXT NOT NULL,
    device_id          TEXT NOT NULL,
    seq                INTEGER NOT NULL,
    stream             TEXT NOT NULL CHECK (stream IN ('device_motion', 'gyro', 'accel', 'magnetometer')),
    source_phone_ns    INTEGER NOT NULL,
    receive_mac_ns     INTEGER NOT NULL,
    q_w REAL, q_x REAL, q_y REAL, q_z REAL,                          -- attitude, ADR 0002
    rotation_rate_x REAL, rotation_rate_y REAL, rotation_rate_z REAL, -- rad/s
    gravity_x REAL, gravity_y REAL, gravity_z REAL,                   -- m/s^2
    user_accel_x REAL, user_accel_y REAL, user_accel_z REAL,          -- m/s^2
    accel_x REAL, accel_y REAL, accel_z REAL,                         -- raw, m/s^2
    magnetic_field_x_ut REAL, magnetic_field_y_ut REAL, magnetic_field_z_ut REAL,
    magnetic_accuracy  TEXT,
    PRIMARY KEY (session_id, device_id, seq),
    FOREIGN KEY (session_id, device_id) REFERENCES devices (session_id, device_id)
) STRICT, WITHOUT ROWID;

CREATE INDEX sensor_samples_by_time ON sensor_samples (session_id, device_id, stream, source_phone_ns);

-- Aligned time is derived, so it lives beside the raw sample, never in it.
CREATE TABLE sample_alignment (
    session_id      TEXT NOT NULL,
    device_id       TEXT NOT NULL,
    seq             INTEGER NOT NULL,
    clock_model_id  TEXT NOT NULL REFERENCES clock_models (clock_model_id),
    aligned_mac_ns  INTEGER NOT NULL,
    uncertainty_ns  INTEGER NOT NULL,
    PRIMARY KEY (session_id, device_id, seq, clock_model_id),
    FOREIGN KEY (session_id, device_id, seq) REFERENCES sensor_samples (session_id, device_id, seq)
) STRICT, WITHOUT ROWID;

-- Ingest and lifecycle events: gaps, duplicates, drops, buffer pressure,
-- parse errors, thermal state, interruptions, reconnects.
CREATE TABLE session_events (
    event_id        INTEGER PRIMARY KEY,
    session_id      TEXT NOT NULL REFERENCES sessions (session_id),
    device_id       TEXT,
    source          TEXT NOT NULL CHECK (source IN ('phone', 'mac')),
    kind            TEXT NOT NULL,
    severity        TEXT NOT NULL CHECK (severity IN ('info', 'warning', 'error')),
    source_ns       INTEGER,                  -- in the source's clock domain
    receive_mac_ns  INTEGER NOT NULL,
    detail          TEXT                      -- JSON object
) STRICT;

CREATE TABLE markers (
    marker_id       TEXT PRIMARY KEY,
    session_id      TEXT NOT NULL REFERENCES sessions (session_id),
    source          TEXT NOT NULL CHECK (source IN ('phone', 'mac', 'operator', 'fixture')),
    label           TEXT NOT NULL,
    source_ns       INTEGER NOT NULL,         -- in the source's clock domain
    source_clock    TEXT NOT NULL CHECK (source_clock IN ('phone', 'mac')),
    notes           TEXT
) STRICT;

-- Mount commands. Created before transmission (ADR 0005).
CREATE TABLE commands (
    command_id             TEXT PRIMARY KEY,
    session_id             TEXT NOT NULL REFERENCES sessions (session_id),
    axis                   TEXT NOT NULL CHECK (axis IN ('azimuth', 'altitude')),
    direction              TEXT NOT NULL CHECK (direction IN ('positive', 'negative', 'stop')),
    requested_rate         REAL,
    requested_rate_unit    TEXT,
    requested_duration_ms  INTEGER,
    requested_mac_ns       INTEGER NOT NULL,
    transmitted_mac_ns     INTEGER,
    acknowledged_mac_ns    INTEGER,
    completed_mac_ns       INTEGER,
    transport              TEXT NOT NULL,
    payload_redacted       TEXT,
    status                 TEXT NOT NULL CHECK (status IN (
                               'requested', 'transmitted', 'acknowledged', 'completed',
                               'cancelled', 'timed_out', 'rejected', 'unknown')),
    rejection_reason       TEXT
) STRICT;

CREATE TABLE mount_events (
    event_id        INTEGER PRIMARY KEY,
    session_id      TEXT NOT NULL REFERENCES sessions (session_id),
    command_id      TEXT REFERENCES commands (command_id),
    mac_ns          INTEGER NOT NULL,
    type            TEXT NOT NULL,
    raw_response    BLOB,
    parsed_fields   TEXT,                     -- JSON object
    severity        TEXT NOT NULL CHECK (severity IN ('info', 'warning', 'error', 'fault'))
) STRICT;

CREATE TABLE derived_results (
    result_id         INTEGER PRIMARY KEY,
    session_id        TEXT NOT NULL REFERENCES sessions (session_id),
    analysis_version  TEXT NOT NULL,
    config_id         TEXT REFERENCES configs (config_id),
    metric_name       TEXT NOT NULL,
    axis              TEXT,
    value             REAL,
    unit              TEXT NOT NULL,
    uncertainty       REAL,
    window_start_ns   INTEGER,
    window_end_ns     INTEGER,
    window_clock      TEXT CHECK (window_clock IN ('phone', 'mac', 'aligned')),
    inputs_hash       TEXT NOT NULL,
    random_seed       INTEGER,
    pass_state        TEXT CHECK (pass_state IN ('pass', 'fail', 'inconclusive', 'not_evaluated')),
    created_utc       TEXT NOT NULL
) STRICT;

CREATE TABLE artifacts (
    artifact_id        TEXT PRIMARY KEY,
    session_id         TEXT NOT NULL REFERENCES sessions (session_id),
    kind               TEXT NOT NULL,
    path               TEXT NOT NULL,         -- relative to the private data root
    sha256             TEXT NOT NULL,
    media_type         TEXT NOT NULL,
    created_utc        TEXT NOT NULL,
    generator_version  TEXT NOT NULL
) STRICT;

-- Raw tables are append-only (ADR 0003).
CREATE TRIGGER sensor_samples_no_update BEFORE UPDATE ON sensor_samples
BEGIN SELECT RAISE(ABORT, 'sensor_samples is append-only'); END;
CREATE TRIGGER sensor_samples_no_delete BEFORE DELETE ON sensor_samples
BEGIN SELECT RAISE(ABORT, 'sensor_samples is append-only'); END;
CREATE TRIGGER clock_sync_no_update BEFORE UPDATE ON clock_sync
BEGIN SELECT RAISE(ABORT, 'clock_sync is append-only'); END;
CREATE TRIGGER clock_sync_no_delete BEFORE DELETE ON clock_sync
BEGIN SELECT RAISE(ABORT, 'clock_sync is append-only'); END;
CREATE TRIGGER mount_events_no_update BEFORE UPDATE ON mount_events
BEGIN SELECT RAISE(ABORT, 'mount_events is append-only'); END;
CREATE TRIGGER mount_events_no_delete BEFORE DELETE ON mount_events
BEGIN SELECT RAISE(ABORT, 'mount_events is append-only'); END;
CREATE TRIGGER markers_no_update BEFORE UPDATE ON markers
BEGIN SELECT RAISE(ABORT, 'markers is append-only'); END;
CREATE TRIGGER markers_no_delete BEFORE DELETE ON markers
BEGIN SELECT RAISE(ABORT, 'markers is append-only'); END;
CREATE TRIGGER session_events_no_update BEFORE UPDATE ON session_events
BEGIN SELECT RAISE(ABORT, 'session_events is append-only'); END;
CREATE TRIGGER session_events_no_delete BEFORE DELETE ON session_events
BEGIN SELECT RAISE(ABORT, 'session_events is append-only'); END;
