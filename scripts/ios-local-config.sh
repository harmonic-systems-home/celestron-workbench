#!/usr/bin/env bash
# Writes ios/ImuLogger/Config/Local.xcconfig (git-ignored) from APPLE_TEAM_ID,
# so the Xcode app can sign without the team ID being committed.
# Optional: CWB_BUNDLE_ID_PREFIX overrides the bundle ID prefix.
set -euo pipefail

if [ -z "${APPLE_TEAM_ID:-}" ]; then
  echo "APPLE_TEAM_ID is not set. Add 'export APPLE_TEAM_ID=...' to your shell profile." >&2
  exit 1
fi

root="$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"
out="$root/ios/ImuLogger/Config/Local.xcconfig"
{
  echo "// Generated by scripts/ios-local-config.sh. Git-ignored; do not commit."
  echo "DEVELOPMENT_TEAM = $APPLE_TEAM_ID"
  if [ -n "${CWB_BUNDLE_ID_PREFIX:-}" ]; then
    echo "CWB_BUNDLE_ID_PREFIX = $CWB_BUNDLE_ID_PREFIX"
  fi
} > "$out"

if ! git -C "$root" check-ignore -q "$out"; then
  echo "error: $out is not git-ignored" >&2
  rm "$out"
  exit 1
fi
echo "Wrote $out"
